from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable
from urllib.parse import urljoin

from bs4 import BeautifulSoup  # type: ignore[import-untyped]


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate RMS brand seed URLs from the saved 'I nostri marchi' HTML.",
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path("providers/html/RMS Ciclo _ I nostri marchi.html"),
        help="Path to the RMS brands HTML snapshot.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("providers/rms_brand_seeds.yaml"),
        help="Destination YAML file for the brand seeds.",
    )
    parser.add_argument(
        "--base-url",
        default="https://b2bnew.rms.it",
        help="Base URL for resolving relative links.",
    )
    return parser.parse_args()


def extract_brands(html: str, base_url: str) -> list[tuple[str, str]]:
    soup = BeautifulSoup(html, "html.parser")
    entries: list[tuple[str, str]] = []
    seen: set[str] = set()
    for link in soup.select("a.menu__link"):
        href = link.get("href") or ""
        if "/category-list/" not in href:
            continue
        img = link.find("img")
        name = (img.get("alt") if img and img.get("alt") else link.get_text()).strip()
        if not name:
            continue
        url = urljoin(base_url, href)
        if url in seen:
            continue
        seen.add(url)
        entries.append((name, url))
    return sorted(entries, key=lambda item: item[0].lower())


def format_yaml(entries: Iterable[tuple[str, str]]) -> str:
    lines = [
        "# Autogenerated by scripts/generate_rms_brand_seeds.py",
        "urls:",
    ]
    for name, url in entries:
        lines.append(f'  - "{url}"  # {name}')
    return "\n".join(lines) + "\n"


def main() -> None:
    args = parse_args()
    html = args.input.read_text(encoding="utf-8")
    entries = extract_brands(html, args.base_url)
    args.output.write_text(format_yaml(entries), encoding="utf-8")
    print(f"Wrote {len(entries)} brand seeds to {args.output}")


if __name__ == "__main__":
    main()
