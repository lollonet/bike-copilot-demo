from __future__ import annotations

import argparse
from pathlib import Path
from typing import Iterable
from urllib.parse import parse_qsl, urljoin, urlsplit, urlunsplit, urlencode

from bs4 import BeautifulSoup


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate a static list of CicloPromo brand seed URLs from a saved HTML file.",
    )
    parser.add_argument(
        "--input",
        type=Path,
        default=Path(
            "providers/html/Ciclo Promo Components _ Distributore di componenti e accessori per il ciclismo.html",
        ),
        help="Path to the saved CicloPromo HTML page.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=Path("providers/ciclopromo_brand_seeds.yaml"),
        help="Destination file that will contain the YAML list.",
    )
    parser.add_argument(
        "--base-url",
        default="https://shop.ciclopromo.com",
        help="Base URL used to resolve relative links.",
    )
    parser.add_argument(
        "--with-public-prices",
        action="store_true",
        help="Append publicPrices=true to every generated URL.",
    )
    return parser.parse_args()


def build_url(href: str, base_url: str, add_public_prices: bool) -> str:
    absolute = urljoin(base_url, href)
    parsed = urlsplit(absolute)
    pairs = list(parse_qsl(parsed.query, keep_blank_values=True))
    keys = {key for key, _ in pairs}
    if add_public_prices and "publicPrices" not in keys:
        pairs.append(("publicPrices", "true"))
    new_query = urlencode(pairs, doseq=True)
    return urlunsplit((parsed.scheme, parsed.netloc, parsed.path, new_query, parsed.fragment))


def sanitize_brand(raw: str) -> str:
    cleaned = raw.strip().strip("|")
    return cleaned or "unknown"


def extract_entries(html: str, base_url: str, add_public_prices: bool) -> list[tuple[str, str]]:
    soup = BeautifulSoup(html, "html.parser")
    results: list[tuple[str, str]] = []
    seen: set[str] = set()
    for anchor in soup.find_all("a"):
        href = anchor.get("href")
        if not href or "brands=" not in href:
            continue
        url = build_url(href, base_url, add_public_prices)
        if url in seen:
            continue
        seen.add(url)
        query = dict(parse_qsl(urlsplit(url).query))
        brand = sanitize_brand(query.get("brands", ""))
        if brand == "unknown":
            text_label = anchor.get_text(strip=True)
            if text_label:
                brand = text_label
        results.append((brand, url))
    return sorted(results, key=lambda item: item[0].lower())


def format_yaml(entries: Iterable[tuple[str, str]]) -> str:
    lines = [
        "# Autogenerated by scripts/generate_ciclopromo_brand_seeds.py",
        "urls:",
    ]
    for brand, url in entries:
        comment = brand.replace('"', "'")
        lines.append(f'  - "{url}"  # {comment}')
    return "\n".join(lines) + "\n"


def main() -> None:
    args = parse_args()
    html = args.input.read_text(encoding="utf-8")
    entries = extract_entries(html, args.base_url, args.with_public_prices)
    args.output.write_text(format_yaml(entries), encoding="utf-8")
    print(f"Wrote {len(entries)} seed URLs to {args.output}")


if __name__ == "__main__":
    main()
